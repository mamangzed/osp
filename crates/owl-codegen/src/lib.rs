// ---------- PHP ----------

fn emit_php(proto_files: &[PathBuf], out_dir: &Path) -> Result<()> {
    let php_pkg = out_dir.join("Osp").join("V1");
    std::fs::create_dir_all(&php_pkg)?;
    copy_protos(proto_files, out_dir)?;
    std::fs::write(out_dir.join("Osp.php"), PHP_WRAPPER)?;
    Ok(())
}

