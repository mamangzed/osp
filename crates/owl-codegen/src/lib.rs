// ---------- Dart ----------

fn emit_dart(proto_files: &[PathBuf], out_dir: &Path) -> Result<()> {
    copy_protos(proto_files, out_dir)?;
    std::fs::write(out_dir.join("osp.dart"), DART_WRAPPER)?;
    Ok(())
}

